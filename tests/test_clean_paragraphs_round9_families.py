def test_the_round9_constants_match_the_ts_side() -> None:
    assert shim.COOKIE_BODY_MIN_LINES == 3
    assert shim.BYLINE_LEAD_PATTERN == r"^[\s*]*(por|by|de|da)\s*:?(\s+\S+){1,3}\s*$"
