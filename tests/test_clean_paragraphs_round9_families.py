def test_the_timesofisrael_appeal_module_is_stripped_from_the_dom() -> None:
    appeal = (
        "We're really pleased that you've read 10 Times of Israel articles in the "
        "past month."
    )
    html = (
        "<html><head>"
        '<meta property="og:title" content="Tanker alert">'
        "</head><body><article>"
        f"<p>{C}</p><p>{A}</p>"
        f'<div class="crm-post-module" style="display:none"><p>{appeal}</p></div>'
        "</article></body></html>"
    )
    _title, paragraphs = _extract(html, "www.timesofisrael.com")
    assert appeal not in paragraphs
    assert paragraphs == [C, A]
